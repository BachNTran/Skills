"""Shared fixtures for the wiki skill tests (read-only for every package but WP1).

- `WK/scripts` goes on sys.path, so tests `import wikimap…` directly.
- `poly`: tmp copy of tests/fixtures/poly plus generated-only files (lint-safe names in the repo):
  extra/src/long.c (6000 lines), extra/src/blob.bin (NUL bytes), web/src/lib/index.ts (JS index probe).
- `plain`: tmp copy of `poly` without modgate.yaml, module cards (X/X.md) and docs/ dirs, plus
  generated README.md overviews (root, core, web).
- `example`: tmp copy of example/weather-station without .wiki/.wikimap.
- `run_cli(args, stdin=None, cwd=None)`: calls `wikimap.cli.main(argv)` in-process -> (code, out, err).
- autouse: XDG_CACHE_HOME points into tmp so no test writes to the real ~/.cache.
"""
from __future__ import annotations

import contextlib
import importlib
import importlib.util
import io
import os
import shlex
import shutil
import sys
from pathlib import Path

import pytest

WK = Path(__file__).resolve().parents[1]
SCRIPTS = WK / "scripts"
FIXTURES = Path(__file__).resolve().parent / "fixtures"
POLY_SRC = FIXTURES / "poly"
REPO = WK.parents[3]
EXAMPLE_SRC = REPO / "example" / "weather-station"

if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

# The fixture trees hold test-shaped code (svc/pkg/test/test_core.py) that is data, not tests.
collect_ignore = ["fixtures"]

_SKIP_NAMES = {".wiki", ".wikimap", ".docmap", "__pycache__", ".pytest_cache"}

LONG_C_LINES = 6000

LIB_INDEX_TS = '''/** Helper exported from a directory index (generated by conftest). */
export function helper(): string {
  return "lib";
}
'''

PLAIN_READMES = {
    "README.md": '''# poly

Plain-mode copy of the poly fixture: no modgate.yaml, units come from manifests.

## Architecture

```mermaid
flowchart LR
  CORE["core"] -- "Sample · call · 1/s" --> SVC["svc"]
  WEB["web"] -- "GET /v1/latest" --> SVC
  WEB --> PROTO["proto"]
  OP["Operator"]:::ext -.-> WEB
```
''',
    "core/README.md": '''# core

C and C++ sources: `c` (numeric helpers) and `geo` (shapes).
''',
    "web/README.md": '''# web

TypeScript front end that fetches `/v1/latest`.
''',
}


def _ignore(_dir, names):
    return [n for n in names if n in _SKIP_NAMES]


def _long_c() -> str:
    out = []
    for i in range(LONG_C_LINES // 6):
        out += [f"int f{i}(int x) {{", f"    int y = x + {i};", f"    y = helper{i % 10}(y);",
                "    return y * 2;", "}", ""]
    return "\n".join(out[:LONG_C_LINES]) + "\n"


def make_poly(dest: Path) -> Path:
    shutil.copytree(POLY_SRC, dest, ignore=_ignore)
    (dest / "extra" / "src" / "long.c").write_text(_long_c(), encoding="utf-8")
    (dest / "extra" / "src" / "blob.bin").write_bytes(b"\x00\x01\x02binary\x00blob\xff\xfe" * 64)
    lib = dest / "web" / "src" / "lib"
    lib.mkdir(parents=True, exist_ok=True)
    (lib / "index.ts").write_text(LIB_INDEX_TS, encoding="utf-8")
    return dest


def make_plain(dest: Path) -> Path:
    make_poly(dest)
    (dest / "modgate.yaml").unlink(missing_ok=True)
    root_name = POLY_SRC.name  # module cards are judged by the source layout (poly/poly.md)
    for dp, dn, fn in os.walk(dest, topdown=True):
        here = Path(dp)
        if "docs" in dn:
            shutil.rmtree(here / "docs")
            dn.remove("docs")
        name = root_name if here == dest else here.name
        for f in fn:
            if f.lower() == f"{name.lower()}.md":
                (here / f).unlink()
    for rel, text in PLAIN_READMES.items():
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    return dest


@pytest.fixture(autouse=True)
def _isolated_cache(tmp_path_factory, monkeypatch):
    monkeypatch.setenv("XDG_CACHE_HOME", str(tmp_path_factory.getbasetemp() / "xdg-cache"))


@pytest.fixture
def poly(tmp_path) -> Path:
    """Fresh tmp copy of the modgate-mode poly fixture (with generated files)."""
    return make_poly(tmp_path / "poly")


@pytest.fixture
def plain(tmp_path) -> Path:
    """Plain-mode variant of poly: no modgate.yaml, no module cards, no docs/, README overviews."""
    return make_plain(tmp_path / "plain")


@pytest.fixture
def example(tmp_path) -> Path:
    """Fresh tmp copy of example/weather-station (no .wiki/.wikimap)."""
    if not EXAMPLE_SRC.is_dir():
        pytest.skip("example/weather-station missing")
    dest = tmp_path / "weather-station"
    shutil.copytree(EXAMPLE_SRC, dest, ignore=_ignore, symlinks=True)
    return dest


@pytest.fixture
def run_cli():
    """Return run(args, stdin=None, cwd=None) -> (exit code, stdout, stderr) via wikimap.cli.main."""
    try:
        spec = importlib.util.find_spec("wikimap.cli")
    except ModuleNotFoundError:
        spec = None
    if spec is None:
        pytest.skip("wikimap.cli not available")
    cli = importlib.import_module("wikimap.cli")

    def run(args, stdin: str | None = None, cwd: Path | str | None = None):
        argv = shlex.split(args) if isinstance(args, str) else [str(a) for a in args]
        out, err = io.StringIO(), io.StringIO()
        old_in, old_cwd = sys.stdin, os.getcwd()
        sys.stdin = io.StringIO(stdin or "")
        try:
            if cwd is not None:
                os.chdir(cwd)
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                try:
                    code = cli.main(argv)
                except SystemExit as e:
                    code = e.code if isinstance(e.code, int) else (0 if e.code is None else 2)
        finally:
            sys.stdin = old_in
            os.chdir(old_cwd)
        return (0 if code is None else code), out.getvalue(), err.getvalue()

    return run
