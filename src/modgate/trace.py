"""The generated `<module>.trace.md`: matrix view + the tool's persistent state block."""

from __future__ import annotations

import datetime as dt
import platform
import re
import shutil
import subprocess
import sys
from pathlib import Path

from ._vendor import yaml

from .hashing import short

STATE_RE = re.compile(r"```yaml\n(modgate-state:.*?)\n```", re.S)


def load_state(path: Path) -> dict:
    if not path.is_file():
        return {}
    m = STATE_RE.search(path.read_text(encoding="utf-8"))
    if not m:
        return {}
    data = yaml.safe_load(m.group(1)) or {}
    return data.get("modgate-state") or {}


def dump_state(state: dict) -> str:
    body = yaml.safe_dump({"modgate-state": state}, sort_keys=True, default_flow_style=False, allow_unicode=True)
    return body.rstrip("\n")


def render(a) -> str:
    """a: analyze.ModuleAnalysis."""
    m = a.module
    approved = a.state.get("module_hash")
    lines = [
        f"# {m.name} · trace",
        "",
        f"State: **{a.status}** · module `{short(a.module_hash)}` · approved `{short(approved)}`"
        f" · kind {m.kind} · {a.criticality or 'criticality unset'}",
        "",
        "> Generated by `modgate sync` — never edit by hand. The yaml block at the end is modgate's state.",
        "",
    ]
    targets = m.targets
    head = ["FEAT", "REQ", "Test cases", *targets]
    lines += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    results = []
    for t in targets:
        rec = (a.state.get("tests") or {}).get(t)
        if rec and rec.get("module_hash") == a.module_hash:
            results.append(f"✓ {rec.get('result', 'pass')}")
        elif rec:
            results.append(f"old ({short(rec.get('module_hash'))})")
        else:
            results.append("–")
    feats = set(a.features)
    rows = []
    for rid, req in sorted(a.reqs.items()):
        parents = req["parents"] or ["–"]
        tcs = a.tests.get(rid, [])
        tc = "<br>".join(f"`{t}`" for t in tcs) if tcs else "–"
        rows.append((", ".join(parents), rid, tc))
    for fid in sorted(feats - {p for r in a.reqs.values() for p in r["parents"]}):
        rows.append((fid, "–", "–"))
    for feat, rid, tc in sorted(rows):
        lines.append("| " + " | ".join([feat, rid, tc, *results]) + " |")
    if not rows:
        lines.append("| – | – | – |" + " – |" * len(targets))
    lines += ["", "```yaml", dump_state(a.state), "```", ""]
    return "\n".join(lines)


def write_if_changed(path: Path, text: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def _first_line(cmd: list[str]) -> str | None:
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return None
    first = (out.stdout or out.stderr).strip().splitlines()
    return first[0].strip() if first else None


def environment() -> dict:
    system = platform.system()
    version = platform.mac_ver()[0] if system == "Darwin" else platform.release()
    env = {
        "os": f"{'macOS' if system == 'Darwin' else system} {version}".strip(),
        "arch": platform.machine(),
        "endianness": sys.byteorder,
        "python": platform.python_version(),
    }
    if shutil.which("c++"):
        cc = _first_line(["c++", "--version"])
        if cc:
            env["compiler"] = cc
    return env


def run_target(cmd: str, cwd: Path, log: Path, timeout: int = 1800) -> tuple[bool, str]:
    """Run a target command; return (passed, result summary). Full output goes to `log`."""
    log.parent.mkdir(parents=True, exist_ok=True)
    try:
        p = subprocess.run(cmd, shell=True, cwd=cwd, capture_output=True, text=True, timeout=timeout)
        out, code = (p.stdout or "") + (p.stderr or ""), p.returncode
    except subprocess.TimeoutExpired:
        out, code = f"timeout after {timeout}s", 124
    log.write_text(out, encoding="utf-8")
    counts = re.findall(r"(\d+) passed|^ℹ pass (\d+)$", out, re.M)  # pytest / GoogleTest shim · node --test
    tail = f" ({counts[-1][0] or counts[-1][1]} passed)" if counts else ""
    return code == 0, ("pass" + tail) if code == 0 else f"fail (exit {code})"


def today() -> str:
    return dt.date.today().isoformat()
