#!/usr/bin/env python3
"""Generate per-feature TRACE.md traceability indexes from workflow artifacts.

For each ``ProjectManagement/features/FEAT-*/`` folder this scans:

* ``DECISIONS.md``  → ``DEC-###`` entries (title, status, serves, superseded_by)
* ``PRD.md``        → ``REQ-###`` blocks (EARS statement, priority, ``from:`` DECs)
* ``TEST_PLAN.md``  → ``TC-###`` cases and the ``REQ-###`` they reference
* the source tree   → ``@covers FEAT-NNNN:REQ-###`` annotations

and writes a generated ``TRACE.md`` into the feature folder: requirement and
decision tables with bidirectional links, a Mermaid graph, and an orphan report
(uncovered requirements, orphan tests, decisions tied to nothing, dangling
``@covers``).

Stdlib only. Idempotent. The output file is generated — do not hand-edit it.

Usage::

    python3 tools/trace_index.py [PROJECT_ROOT] [--check]

``--check`` exits non-zero if any orphans are found (useful as a CI / hook gate).
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

DEC_HEADER = re.compile(r"^##\s+(DEC-\d+)\s*(?:[—–-]\s*(.*))?\s*$")
REQ_HEADER = re.compile(r"^###\s+(REQ-\d+)\s*(?:[—–-]\s*(.*))?\s*$")
FIELD = re.compile(r"^\s*[-*]\s*\*\*(?P<key>[\w -]+?):\*\*\s*(?P<val>.*?)\s*$")
TC_TOKEN = re.compile(r"TC-\d+")
REQ_TOKEN = re.compile(r"REQ-\d+")
DEC_TOKEN = re.compile(r"DEC-\d+")
COVERS = re.compile(r"@covers\s+(FEAT-\d+):(REQ-\d+)")
FEAT_ID = re.compile(r"FEAT-\d+")

# Directories never scanned for @covers annotations.
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "venv",
             ".pytest_cache", "ProjectManagement", "dist", "build", ".mypy_cache"}
GENERATED_MARKER = "<!-- GENERATED by tools/trace_index.py — do not hand-edit -->"


@dataclass
class Decision:
    id: str
    title: str = ""
    status: str = "active"
    serves: set[str] = field(default_factory=set)
    superseded_by: str = ""


@dataclass
class Requirement:
    id: str
    name: str = ""
    statement: str = ""
    priority: str = ""
    from_decs: set[str] = field(default_factory=set)


@dataclass
class TestCase:
    id: str
    reqs: set[str] = field(default_factory=set)


def _csv_ids(value: str, token: re.Pattern[str]) -> set[str]:
    """Pull all IDs of a kind out of a field value ('REQ-001, REQ-002' → {…})."""
    return set(token.findall(value))


def _iter_blocks(lines: list[str], header: re.Pattern[str]):
    """Yield (header_match, body_lines) for each header-delimited block."""
    current: tuple[re.Match[str], list[str]] | None = None
    for line in lines:
        m = header.match(line)
        if m:
            if current:
                yield current
            current = (m, [])
        elif current:
            current[1].append(line)
    if current:
        yield current


def _fields(body: list[str]) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in body:
        fm = FIELD.match(line)
        if fm:
            out[fm.group("key").strip().lower()] = fm.group("val").strip()
    return out


def _first_id(value: str, token: re.Pattern[str]) -> str:
    m = token.search(value)
    return m.group(0) if m else ""


def parse_decisions(path: Path) -> dict[str, Decision]:
    decs: dict[str, Decision] = {}
    if not path.exists():
        return decs
    for header, body in _iter_blocks(path.read_text().splitlines(), DEC_HEADER):
        dec_id = header.group(1)
        f = _fields(body)
        status_val = f.get("status", "") or "active"
        decs[dec_id] = Decision(
            id=dec_id,
            title=(header.group(2) or "").strip(),
            status=status_val.split()[0],
            serves=_csv_ids(f.get("serves", ""), REQ_TOKEN),
            superseded_by=_first_id(f.get("superseded_by", ""), DEC_TOKEN),
        )
    return decs


def parse_prd(path: Path) -> dict[str, Requirement]:
    reqs: dict[str, Requirement] = {}
    if not path.exists():
        return reqs
    for header, body in _iter_blocks(path.read_text().splitlines(), REQ_HEADER):
        req_id = header.group(1)
        f = _fields(body)
        reqs[req_id] = Requirement(
            id=req_id,
            name=(header.group(2) or "").strip(),
            statement=f.get("statement (ears)", f.get("statement", "")),
            priority=f.get("priority", ""),
            from_decs=_csv_ids(f.get("from", ""), DEC_TOKEN),
        )
    return reqs


def parse_test_plan(path: Path) -> dict[str, TestCase]:
    """Associate each TC-### with any REQ-### appearing on the same line."""
    cases: dict[str, TestCase] = {}
    if not path.exists():
        return cases
    for line in path.read_text().splitlines():
        tcs = TC_TOKEN.findall(line)
        if not tcs:
            continue
        reqs = set(REQ_TOKEN.findall(line))
        for tc in tcs:
            cases.setdefault(tc, TestCase(id=tc)).reqs |= reqs
    return cases


def scan_covers(root: Path, feat_id: str) -> dict[str, list[str]]:
    """Map REQ-### → ['relpath:line', …] from @covers annotations for this feature."""
    hits: dict[str, list[str]] = {}
    for path in root.rglob("*"):
        if path.is_dir() or any(part in SKIP_DIRS for part in path.parts):
            continue
        try:
            text = path.read_text(errors="ignore")
        except (OSError, UnicodeDecodeError):
            continue
        if "@covers" not in text:
            continue
        for i, line in enumerate(text.splitlines(), 1):
            for fid, req in COVERS.findall(line):
                if fid == feat_id:
                    hits.setdefault(req, []).append(f"{path.relative_to(root)}:{i}")
    return hits


def _md_link(target: str, anchor: str) -> str:
    return f"[{anchor}]({target})"


def build_trace(feat_dir: Path, root: Path) -> tuple[str, list[str]]:
    """Return (TRACE.md content, orphan messages) for one feature folder."""
    feat_match = FEAT_ID.search(feat_dir.name)
    feat_id = feat_match.group(0) if feat_match else feat_dir.name
    decs = parse_decisions(feat_dir / "DECISIONS.md")
    reqs = parse_prd(feat_dir / "PRD.md")
    tcs = parse_test_plan(feat_dir / "TEST_PLAN.md")
    covers = scan_covers(root, feat_id)

    # Reverse maps.
    req_to_tcs: dict[str, set[str]] = {r: set() for r in reqs}
    for tc in tcs.values():
        for r in tc.reqs:
            req_to_tcs.setdefault(r, set()).add(tc.id)

    orphans: list[str] = []

    # --- Requirements table ---
    lines = [
        GENERATED_MARKER,
        f"# TRACE — {feat_id}",
        "",
        "Generated traceability index. Source of truth is `DECISIONS.md`, `PRD.md`, "
        "`TEST_PLAN.md`, and `@covers` annotations in the code. Regenerate with "
        "`python3 tools/trace_index.py`.",
        "",
        "## Requirements",
        "",
        "| REQ | Name | Priority | from (DEC) | proven-by (TC) | covered in code |",
        "|-----|------|----------|------------|----------------|-----------------|",
    ]
    for rid in sorted(reqs):
        r = reqs[rid]
        dec_links = ", ".join(
            _md_link(f"DECISIONS.md#{d.lower()}", d) for d in sorted(r.from_decs)
        ) or "—"
        tc_links = ", ".join(sorted(req_to_tcs.get(rid, set()))) or "—"
        code_links = ", ".join(
            _md_link(f"../../../{p.rsplit(':', 1)[0]}", p) for p in covers.get(rid, [])
        ) or "—"
        lines.append(
            f"| {_md_link(f'PRD.md#{rid.lower()}', rid)} | {r.name} | {r.priority or '—'} "
            f"| {dec_links} | {tc_links} | {code_links} |"
        )

    # --- Decisions table ---
    lines += [
        "",
        "## Decisions",
        "",
        "| DEC | Title | Status | serves (REQ) |",
        "|-----|-------|--------|--------------|",
    ]
    for did in sorted(decs):
        d = decs[did]
        serves = ", ".join(sorted(d.serves)) or "—"
        status = d.status + (f" → {d.superseded_by}" if d.superseded_by else "")
        lines.append(
            f"| {_md_link(f'DECISIONS.md#{did.lower()}', did)} | {d.title} | {status} | {serves} |"
        )

    # --- Mermaid graph ---
    lines += ["", "## Graph", "", "```mermaid", "graph LR"]
    for did, d in sorted(decs.items()):
        for r in sorted(d.serves):
            lines.append(f"  {did} --> {r}")
    for rid in sorted(reqs):
        for tc in sorted(req_to_tcs.get(rid, set())):
            lines.append(f"  {rid} --> {tc}")
        if covers.get(rid):
            lines.append(f"  {rid} --> code_{rid.replace('-', '_')}[\"{len(covers[rid])} code site(s)\"]")
    lines.append("```")

    # --- Orphan report ---
    lines += ["", "## Orphan report", ""]
    report: list[str] = []
    for rid, r in sorted(reqs.items()):
        if not req_to_tcs.get(rid):
            report.append(f"- ⚠️ **{rid}** has no test case (uncovered requirement)")
        if not covers.get(rid):
            report.append(f"- ⚠️ **{rid}** has no `@covers` annotation in code (not traced to implementation)")
        if not r.from_decs:
            report.append(f"- ℹ️ **{rid}** has no `from:` decision (no recorded rationale)")
    for tcid, tc in sorted(tcs.items()):
        unknown = {r for r in tc.reqs if r not in reqs}
        if not tc.reqs:
            report.append(f"- ⚠️ **{tcid}** names no requirement (orphan test)")
        for u in sorted(unknown):
            report.append(f"- ⚠️ **{tcid}** references unknown {u}")
    for rid in sorted(covers):
        if rid not in reqs:
            report.append(f"- ⚠️ `@covers` points at unknown **{rid}** ({', '.join(covers[rid])})")
    for did, d in sorted(decs.items()):
        if d.status == "active" and not d.serves:
            report.append(f"- ℹ️ **{did}** serves no requirement yet")

    if report:
        lines += report
        orphans = [m for m in report if "⚠️" in m]
    else:
        lines.append("✅ No orphans. Every requirement is tested and traced; every test names a requirement.")
    lines.append("")
    return "\n".join(lines), orphans


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("root", nargs="?", default=".", help="project root (default: cwd)")
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if any feature has orphan warnings")
    args = ap.parse_args(argv)

    root = Path(args.root).resolve()
    features_dir = root / "ProjectManagement" / "features"
    if not features_dir.is_dir():
        print(f"No {features_dir} — nothing to trace.", file=sys.stderr)
        return 0

    total_orphans = 0
    wrote = 0
    for feat_dir in sorted(features_dir.iterdir()):
        if not feat_dir.is_dir() or not FEAT_ID.search(feat_dir.name):
            continue
        content, orphans = build_trace(feat_dir, root)
        (feat_dir / "TRACE.md").write_text(content)
        wrote += 1
        total_orphans += len(orphans)
        status = f"{len(orphans)} orphan warning(s)" if orphans else "clean"
        print(f"  {feat_dir.name}/TRACE.md — {status}")

    print(f"Wrote {wrote} TRACE.md file(s); {total_orphans} orphan warning(s) total.")
    if args.check and total_orphans:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
